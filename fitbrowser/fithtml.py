"""
Generate HTML information.
"""

import re
import html
import datetime
from os import path

if __package__ == "fitbrowser":
    from . import activity
    from . import fitcss
else:
    import activity
    import fitcss

class FitHtmlFormatter:
    cssUrl = "fitbrowser.css"
    lineTerminator = "\n"
    regexForFileName = re.compile("/?([0-9]{4})-?([0-9]{2})?\\.html")
    regexForLocation = re.compile("/?location/(([-+])?[0-9]+(.[0-9]+)?),(([-+])?[0-9]+(.[0-9]+)?)\\.html")
    regexForActivity = re.compile("/?activity/([-+.:TZ0-9]+)\\.html")

    googleMapsIntegrationMagic = """
    <script>
        // prettier-ignore
        // Defines window.initGoogleMapsLoader without invoking it - index.js
        // calls it once it has fetched the API key from gmapikey.json.
        window.initGoogleMapsLoader = (g=>{var h,a,k,p="The Google Maps JavaScript API",c="google",l="importLibrary",q="__ib__",m=document,b=window;b=b[c]||(b[c]={});var d=b.maps||(b.maps={}),r=new Set,e=new URLSearchParams,u=()=>h||(h=new Promise(async(f,n)=>{await (a=m.createElement("script"));e.set("libraries",[...r]+"");for(k in g)e.set(k.replace(/[A-Z]/g,t=>"_"+t[0].toLowerCase()),g[k]);e.set("callback",c+".maps."+q);a.src=`https://maps.${c}apis.com/maps/api/js?`+e;d[q]=f;a.onerror=()=>h=n(Error(p+" could not load."));a.nonce=m.querySelector("script[nonce]")?.nonce||"";m.head.append(a)}));d[l]?console.warn(p+" only loads once. Ignoring:",g):d[l]=(f,...n)=>r.add(f)&&u().then(()=>d[l](f,...n))});
    </script>
    """

    overviewInitMagic = """
    <script type="module">
        import { init } from '/overview.js';
        init(document.location);
    </script>
    """
    
    activityInitMagic = """
    <script type="module">
        import { init } from '/activity.js';
        init(document.location);
    </script>
    """
    
    def __init__(self, config, activities, groupedActivities, geoLocator, groupRadiusKm):
        self.css = None
        self.formatForYear = "%Y"
        self.formatForMonth = "%B"
        self.formatForDay = "%B %d, %Y"
        self.activities = activities
        self.groupedActivities = groupedActivities
        self.geoLocator = geoLocator
        self.groupRadiusKm = groupRadiusKm
        self.configure(config)

    def configure(self, configData):
        self.config = configData

        if ("cssFileName" in self.config) and ("builtinCss" in self.config):
            self.css = fitcss.makeCssProvider(self.config["cssFileName"], self.config["builtinCss"])
        else:
            self.css = None

    @staticmethod
    def joinLines(lines):
        result = ""
        for line in lines:
            result += line
            result += FitHtmlFormatter.lineTerminator
        return result

    def htmlHeader(self, title=None):
        headerLines = [
            "<!DOCTYPE html>"
            "<html>",
            "<head>"
        ]

        if self.css:
            headerLines.append(f"<link rel=\"stylesheet\" href=\"/{FitHtmlFormatter.cssUrl}\">")

        if title:
            headerLines.append("<title>{0}</title>".format(html.escape(title)))

        headerLines.extend([
            "</head>",
            "<body>"
        ])
        return FitHtmlFormatter.joinLines(headerLines)

    def htmlFooter(self):
        now = datetime.datetime.now()
        timestamp = now.isoformat(" ", "seconds")

        footerLines = [
            "<hr>"
            "Generated by FitBrowser at " + timestamp + ".",
            "</body>",
            "</html>"
        ]
        return FitHtmlFormatter.joinLines(footerLines)

    def formatDay(self, date):
        return date.strftime(self.formatForDay)

    def formatMonth(self, date):
        return date.strftime(self.formatForMonth)

    def anchorMonth(self, year, month):
        return "{0:04d}-{1:02d}".format(year, month)

    def linkMonth(self, toYear, toMonth):
        url = "{0:04d}.html#".format(toYear, toMonth)
        url += self.anchorMonth(toYear, toMonth)
        return url

    def anchorYear(self, year):
        return "{0:04d}".format(year)

    def linkYear(self, toYear):
        return "{0:04d}.html".format(toYear)

    def formatYear(self, date):
        return date.strftime(self.formatForYear)

    def formatDayAndTime(self, timestamp):
        return timestamp.strftime("%b %d, %H:%M")

    def formatDuration(self, elapsedSeconds):
        totalSeconds = int(elapsedSeconds)
        totalHours = int(totalSeconds / 3600)
        totalSeconds -= totalHours * 3600
        totalMinutes = int(totalSeconds / 60)
        totalSeconds -= totalMinutes * 60
        formattedDuration = f"{totalHours}:{totalMinutes:02d}:{totalSeconds:02d} hours" if totalHours > 0 else f"{totalMinutes}:{totalSeconds:02d} minutes"
        return formattedDuration

    def formatDistance(self, elapsedMeters):
        formattedDistance = f"{elapsedMeters/1000:.1f} km"
        return formattedDistance
    
    def formatLocation(self, lat, lon):
        if lat is None or lon is None:
            return None
        try:
            place = self.geoLocator.nearest_city(lat, lon)
        except:
            place = None
        if not place:
            return f"{lat:.5f},{lon:.5f}"
        return f"{str(place[1])}, {str(place[0])}"

    def printNavigationHeaders(self, lastTimestamp, thisTimestamp):
        htmlLines = []

        if not thisTimestamp:
            if lastTimestamp:
                htmlLines.append("</ul>")
            return FitHtmlFormatter.joinLines(htmlLines)

        if lastTimestamp:
            differentYear = lastTimestamp.year != thisTimestamp.year
            differentMonth = differentYear or (lastTimestamp.month != thisTimestamp.month)
            differentDay = differentMonth or (lastTimestamp.day != thisTimestamp.day)
        else:
            differentYear = True
            differentMonth = True
            differentDay = True

        if differentMonth:
            if lastTimestamp:
                htmlLines.append("</ul>")

        if differentYear:
            if lastTimestamp:
                htmlLines.append("</dl>")
            htmlLines.append("<h2>")
            htmlLines.append(self.formatYear(thisTimestamp))
            htmlLines.append("</h2>")

        if differentMonth:
            htmlLines.append("<h3 id=\"" + self.anchorMonth(thisTimestamp.year, thisTimestamp.month) + "\">")
            htmlLines.append(self.formatMonth(thisTimestamp))
            htmlLines.append("</h3>")
            htmlLines.append("<ul>")

        return FitHtmlFormatter.joinLines(htmlLines)

    def printActivitySummary(self, activity):
        htmlLines = []
        summaryData = activity.summary()
        timestampForLink = activity.time().isoformat()
        hasTrack = len(activity.records()) > 0
        htmlLines.append("<li>")
        if hasTrack:
            htmlLines.append("<a href=\"/activity/" + timestampForLink + ".html\">")
        htmlLines.append(self.formatDayAndTime(activity.time()))
        if hasTrack:
            htmlLines.append("</a> ")
        htmlLines.append(self.formatDistance(summaryData["distance_m"]))
        htmlLines.append(summaryData["sport"].capitalize())
        htmlLines.append(self.formatDuration(summaryData["duration_s"]))
        locationName = self.formatLocation(summaryData["start_lat"], summaryData["start_lng"])
        if locationName:
            htmlLines.append(locationName)
        return FitHtmlFormatter.joinLines(htmlLines)

    def cumulateActivitiesForMonth(self, year, month):
        activityIndex = self.activities.findByTimestamp(datetime.date(year, month, 1))

        activityCount = 0
        activitySports = dict()
        activityLocations = set()

        while activityIndex != -1 and activityIndex < len(self.activities):
            activity = self.activities[activityIndex]
            if activity.time().year != year or activity.time().month != month:
                break
            activityCount += 1
            summary = activity.summary()
            sport = summary["sport"]
            if sport not in activitySports:
                activitySports[sport] = {"count": 0, "distance_m": 0, "duration_s": 0}
            activitySports[sport]["count"] += 1
            if "distance_m" in summary and summary["distance_m"] != None:
                activitySports[sport]["distance_m"] += summary["distance_m"]
            if "duration_s" in summary and summary["duration_s"] != None:
                activitySports[sport]["duration_s"] += summary["duration_s"]
            location = self.formatLocation(summary["start_lat"], summary["start_lng"])
            if location is not None:
                activityLocations.add(location)
            activityIndex += 1

        return {
            "count": activityCount,
            "sports": activitySports,
            "locations": activityLocations
        }

    #
    # Top-level index.html.
    #
    
    def generateIndexHtml(self, outputFile):
        htmlLines = [
            "<!DOCTYPE html>",
            "<html>",
            "<head>",
            f"<link rel=\"stylesheet\" href=\"/{FitHtmlFormatter.cssUrl}\">",
            "<title>Activity Overview</title>"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        outputFile.write(FitHtmlFormatter.googleMapsIntegrationMagic.encode())
        outputFile.write(FitHtmlFormatter.overviewInitMagic.encode())

        htmlLines = [
            "</head>",
            "<body>",
            "<h1>Activity Overview</h1>",
            "<div id=\"map\"></div>",
            "<div id=\"info\">"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        
        lastYear = None
        thisYear, thisMonth = self.activities.calendar.getFirstMonth()

        htmlLines = []
        while thisMonth is not None:
            differentYear = (lastYear is None) or (lastYear != thisYear)

            if differentYear:
                htmlLines.append("<h2>")
                htmlLines.append("<a href=\"" + self.linkYear(thisYear) + "\">")
                htmlLines.append(self.formatYear(datetime.date(thisYear, 1, 1)))
                htmlLines.append("</a>")
                htmlLines.append("</h2>")
                htmlLines.append("<table class=\"overview\">")
                htmlLines.append("<tr class=\"overview-row\">")
                htmlLines.append("<th class=\"overview-month\">Month</th>")
                htmlLines.append("<th class=\"overview-activities\">Activities</th>")
                htmlLines.append("<th class=\"overview-locations\">Locations</th>")
                htmlLines.append("</tr>")

            monthlyData = self.cumulateActivitiesForMonth(thisYear, thisMonth)

            htmlLines.append("<tr class=\"overview\">")
            htmlLines.append("<td class=\"overview-month\">")
            htmlLines.append("<a href=\"" + self.linkMonth(thisYear, thisMonth) + "\">")
            htmlLines.append(self.formatMonth(datetime.date(thisYear, thisMonth, 1)))
            htmlLines.append("</a>")
            htmlLines.append("</td>")

            htmlLines.append("<td class=\"overview-activities\">")
            firstSport = True
            for sport in monthlyData["sports"].keys():
                if firstSport:
                    firstSport = False
                else:
                    htmlLines.append("<br>")
                sportData = monthlyData["sports"][sport]
                info = str(sportData["count"])
                info += "x " + sport.capitalize()

                if sportData["duration_s"] != 0:
                    info += ", " + self.formatDuration(sportData["duration_s"])

                if sportData["distance_m"] != 0:
                    info += ", " + self.formatDistance(sportData["distance_m"])

                htmlLines.append(info)
            htmlLines.append("</td>")

            locationList = ""
            for location in monthlyData["locations"]:
                if locationList != "":
                    locationList += "; "
                locationList += location
            htmlLines.append("<td class=\"overview-activities\">" + locationList + "</td>")
            htmlLines.append("</tr>")

            lastMonth = thisMonth
            lastYear = thisYear
            thisYear, thisMonth = self.activities.calendar.getNextMonth(thisYear, thisMonth)

            if thisYear != lastYear:
                htmlLines.append("</table>")

        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())

        if lastYear is None:
            htmlLines = "<b>No activities.</b>"
            outputFile.write(htmlLines.encode())


        htmlLines = [
            "</div>"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        htmlLines = self.htmlFooter()
        outputFile.write(htmlLines.encode())

    #
    # Annual page.
    #
    
    def generateAnnualPage(self, year, outputFile):
        title = f"Activities in {year}"
        htmlLines = self.htmlHeader(title)
        outputFile.write(htmlLines.encode())

        infoLines = []
        infoLines.append("<h1 class=\"annual-title\">")
        infoLines.append(title)
        infoLines.append("</h1>")
        outputFile.write(FitHtmlFormatter.joinLines(infoLines).encode())
        
        lastActivityTimestamp = None
        activityIndex = self.activities.findByTimestamp(datetime.date(year, 1, 1))

        while activityIndex != -1 and activityIndex < len(self.activities):
            activity = self.activities[activityIndex]
            if activity.time().year != year:
                break

            htmlLines = self.printNavigationHeaders(lastActivityTimestamp, activity.time())
            outputFile.write(htmlLines.encode())
            htmlLines = self.printActivitySummary(activity)
            outputFile.write(htmlLines.encode())
            lastActivityTimestamp = activity.time()
            activityIndex += 1

        if lastActivityTimestamp is None:
            htmlLines = "<b>No activities.</b>"
            outputFile.write(htmlLines.encode())

        htmlLines = self.printNavigationHeaders(lastActivityTimestamp, None)
        outputFile.write(htmlLines.encode())
        htmlLines = self.htmlFooter()
        outputFile.write(htmlLines.encode())

    #
    # Activities around a location.
    #
    
    def generateLocationPage(self, lat, lon, outputFile):
        locationName = self.formatLocation(lat, lon)
        title = f"Activities near {locationName}" if locationName is not None else None
        htmlLines = self.htmlHeader(title)
        outputFile.write(htmlLines.encode())

        infoLines = []
        infoLines.append("<h1 class=\"location-title\">")
        infoLines.append(title)
        infoLines.append("</h1>")
        outputFile.write(FitHtmlFormatter.joinLines(infoLines).encode())

        lastActivityTimestamp = None
        locationGroup = self.groupedActivities.find_by_location(lat, lon)
        
        if locationGroup is not None:
            for activity in locationGroup:
                htmlLines = self.printNavigationHeaders(lastActivityTimestamp, activity.time())
                outputFile.write(htmlLines.encode())
                htmlLines = self.printActivitySummary(activity)
                outputFile.write(htmlLines.encode())
                lastActivityTimestamp = activity.time()
        else:
            htmlLines = "<b>No activities.</b>"
            outputFile.write(htmlLines.encode())

        htmlLines = self.printNavigationHeaders(lastActivityTimestamp, None)
        outputFile.write(htmlLines.encode())
        htmlLines = self.htmlFooter()
        outputFile.write(htmlLines.encode())
        
    #
    # Show an activity.
    #
    
    def generateActivitySplitsTable(self, activity, outputFile):
        summary = activity.summary()
        lastSplitRecord = activity.records()[0]
        lastSplitIndex = 0

        infoLines = []
        infoLines.append("<table class=\"activity\">")
        infoLines.append("<tr class=\"activity-row\">")
        infoLines.append("<th class=\"activity-distance\">Distance</th>")
        infoLines.append("<th class=\"activity-time\">Time</th>")
        infoLines.append("<th class=\"activity-split\">Split</th>")
        infoLines.append("<th class=\"activity-elevation\">Elevation</th>")
        infoLines.append("<th class=\"activity-heartrate\">Heart Rate</th>")
        infoLines.append("</tr>")
        
        #
        # Table rows with one row per kilometer.
        #

        splitPos = 1000
        totalDistance = summary["distance_m"]
        while splitPos < totalDistance:
            thisSplitIndex = activity.distance_to_index(splitPos)
            thisSplitRecord = activity.distance_to_record(splitPos)
            if thisSplitRecord is None:
                break
            formattedSplit = self.formatDuration(thisSplitRecord["duration_s"] - lastSplitRecord["duration_s"])
            formattedDuration = self.formatDuration(thisSplitRecord["duration_s"])
            elevationDifference = int(thisSplitRecord["ele"] - lastSplitRecord["ele"])
            averageHeartRate = activity.average_heart_rate(lastSplitIndex, thisSplitIndex)
            averageHeartRate = f"{averageHeartRate:.0f}" if averageHeartRate else ""
            infoLines.append("<tr class=\"activity-row\">")
            infoLines.append(f"<td class=\"activity-distance\">{int(splitPos/1000)}</td>")
            infoLines.append(f"<td class=\"activity-time\">{formattedDuration}</td>")
            infoLines.append(f"<td class=\"activity-split\">{formattedSplit}</td>")
            infoLines.append(f"<td class=\"activity-elevation\">{elevationDifference:+d}</td>")
            infoLines.append(f"<td class=\"activity-heartrate\">{averageHeartRate}</td>")
            infoLines.append("</tr>")
            lastSplitRecord = thisSplitRecord
            lastSplitIndex = thisSplitIndex
            splitPos += 1000

        #
        # Table row with the remainder of the distance.
        #

        thisSplitRecord = activity.records()[-1]
        formattedSplit = self.formatDuration(thisSplitRecord["duration_s"] - lastSplitRecord["duration_s"])
        formattedDuration = self.formatDuration(thisSplitRecord["duration_s"])
        remainingDistance = thisSplitRecord["distance_m"] - lastSplitRecord["distance_m"]
        elevationDifference = int(thisSplitRecord["ele"] - lastSplitRecord["ele"])
        averageHeartRate = activity.average_heart_rate(lastSplitIndex, -1)
        averageHeartRate = f"{averageHeartRate:.0f}" if averageHeartRate else ""
        infoLines.append("<tr class=\"activity-row\">")
        infoLines.append(f"<td class=\"activity-distance\">{(remainingDistance/1000):.2f}</td>")
        infoLines.append(f"<td class=\"activity-time\">{formattedDuration}</td>")
        infoLines.append(f"<td class=\"activity-split\">{formattedSplit}</td>")
        infoLines.append(f"<td class=\"activity-elevation\">{elevationDifference:+d}</td>")
        infoLines.append(f"<td class=\"activity-heartrate\">{averageHeartRate}</td>")
        infoLines.append("</tr>")

        #
        # Table row with totals.
        #

        formattedDuration = self.formatDuration(summary["duration_s"])
        elevationDifference = int(activity.records()[-1]["ele"] - activity.records()[0]["ele"])
        averageHeartRate = activity.average_heart_rate(0, -1)
        averageHeartRate = f"{averageHeartRate:.0f}" if averageHeartRate else ""
        infoLines.append("<tr class=\"activity-row\">")
        infoLines.append(f"<td class=\"activity-distance\">{(summary['distance_m']/1000):.2f}</td>")
        infoLines.append(f"<td class=\"activity-time\">{formattedDuration}</td>")
        infoLines.append(f"<td class=\"activity-split\"></td>")
        infoLines.append(f"<td class=\"activity-elevation\">{elevationDifference:+d}</td>")
        infoLines.append(f"<td class=\"activity-heartrate\">{averageHeartRate}</td>")
        infoLines.append("</tr>")

        infoLines.append("</table>")
        outputFile.write(FitHtmlFormatter.joinLines(infoLines).encode())

    def generateActivityPage(self, timestamp, outputFile):
        activity = self.activities[timestamp]
        summary = activity.summary()

        title = summary["sport"].capitalize()
        locationName = self.formatLocation(summary["start_lat"], summary["start_lng"])
        if locationName:
            title += " near " + locationName
        title += " on " + self.formatDayAndTime(activity.time())
        
        htmlLines = [
            "<!DOCTYPE html>",
            "<html>",
            "<head>",
            f"<link rel=\"stylesheet\" href=\"/{FitHtmlFormatter.cssUrl}\">",
            f"<title>{title}</title>"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        outputFile.write(FitHtmlFormatter.googleMapsIntegrationMagic.encode())
        outputFile.write(FitHtmlFormatter.activityInitMagic.encode())
        
        htmlLines = [
            "</head>",
            "<body>",
            f"<h1>{title}</h1>",
            "<div id=\"map\"></div>",
            "<div id=\"info\">"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        self.generateActivitySplitsTable(self.activities[timestamp], outputFile)
        htmlLines = [
            "</div>"
        ]
        
        outputFile.write(FitHtmlFormatter.joinLines(htmlLines).encode())
        htmlLines = self.htmlFooter()
        outputFile.write(htmlLines.encode())
        
    #
    # Write the CSS document.
    #

    def generateCss(self, outputFile, updatecb=None):
        if not self.css:
            raise Exception("Oops.")
        data = self.css.data.encode()
        outputFile.write(data)
        if updatecb:
            updatecb.update(len(data))

    #
    # Generate a HTML page.
    #

    def generateHtml(self, url, outputFile, updatecb=None):
        oops = False
        fileNameMatch = FitHtmlFormatter.regexForFileName.match(url)
        locationMatch = FitHtmlFormatter.regexForLocation.match(url)
        activityMatch = FitHtmlFormatter.regexForActivity.match(url)

        if url in ("/index.html", "index.html"):
            self.generateIndexHtml(outputFile)
        elif fileNameMatch and fileNameMatch[1]:
            year = int(fileNameMatch[1])
            self.generateAnnualPage(year, outputFile)
        elif locationMatch:
            lat = float(locationMatch[1])
            lon = float(locationMatch[4])
            self.generateLocationPage(lat, lon, outputFile)
        elif activityMatch:
            timestamp = datetime.datetime.fromisoformat(activityMatch[1].replace('Z', '+00:00'))
            self.generateActivityPage(timestamp, outputFile)
        else:
            oops = True

        if oops:
            htmlCode = self.htmlHeader()
            outputFile.write(htmlCode.encode())

            htmlCode = "<b>Oops.</b>"
            outputFile.write(htmlCode.encode())

            htmlCode = self.htmlFooter()
            outputFile.write(htmlCode.encode())

    def isCssUrl(self, url):
        # pylint: disable=consider-using-in
        return self.css is not None and ((url == FitHtmlFormatter.cssUrl) or (url[1:] == FitHtmlFormatter.cssUrl))

    def isHtmlUrl(self, url):
        return url.endswith(".html")

    def hasFile(self, url):
        if url in ("/index.html", "index.html"):
            return True
        elif self.isCssUrl(url):
            return True
        elif FitHtmlFormatter.regexForFileName.match(url):
            return True
        elif FitHtmlFormatter.regexForLocation.match(url):
            return True
        elif FitHtmlFormatter.regexForActivity.match(url):
            return True
        return False

    def copyFile(self, path, outputFile, updatecb=None):
        if self.css is not None and self.isCssUrl(path):
            self.generateCss(outputFile, updatecb)
        elif self.isHtmlUrl(path):
            self.generateHtml(path, outputFile, updatecb)
        else:
            raise Exception("Oops.")
